/* ------------------------------------------------------------------
   WORLD DOTS — turns Natural Earth land polygons into the dot grid of
   the "where I grew up" map (lib/world-dots.ts). Run once, by hand:

     node scripts/build-world-dots.mjs path/to/land-110m.json

   Input: land-110m.json from the world-atlas npm package (TopoJSON,
   Natural Earth, public domain). Each 2° cell becomes a dot when at
   least a third of its 3×3 samples fall on land.
   ------------------------------------------------------------------ */

import { readFile, writeFile } from "node:fs/promises"

const STEP = 2
const LON_START = -179
const LAT_START = 74
const COLS = 180
const ROWS = 66
const SAMPLES = [-0.66, 0, 0.66]
const THRESHOLD = 3

const input = process.argv[2]
if (!input) throw new Error("Usage: node scripts/build-world-dots.mjs path/to/land-110m.json")
const topology = JSON.parse(await readFile(input, "utf8"))

const { scale, translate } = topology.transform
const arcs = topology.arcs.map(arc => {
  let x = 0, y = 0
  return arc.map(([dx, dy]) => [(x += dx) * scale[0] + translate[0], (y += dy) * scale[1] + translate[1]])
})
const ring = indexes => indexes.flatMap((i, n) => {
  const points = i >= 0 ? arcs[i] : arcs[~i].slice().reverse()
  return n === 0 ? points : points.slice(1)
})
/** Rings crossing the antimeridian (Russia, Fiji) are made continuous past ±180°. */
const unwrap = points => {
  let prev = points[0][0]
  return points.map(([x, y]) => {
    while (x - prev > 180) x -= 360
    while (x - prev < -180) x += 360
    prev = x
    return [x, y]
  })
}

const polygons = topology.objects.land.geometries.flatMap(g => g.type === "Polygon" ? [g.arcs] : g.arcs).map(p => {
  const rings = p.map(indexes => unwrap(ring(indexes)))
  const all = rings.flat()
  const xs = all.map(q => q[0]), ys = all.map(q => q[1])
  return { rings, box: [Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)] }
})

/** Even-odd test across every ring of a polygon, so lakes stay holes. */
function onLand(lon, lat) {
  return [lon, lon - 360, lon + 360].some(x => inPolygon(x, lat))
}
function inPolygon(lon, lat) {
  for (const { rings, box } of polygons) {
    if (lon < box[0] || lon > box[2] || lat < box[1] || lat > box[3]) continue
    let inside = false
    for (const r of rings) {
      for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
        const [xi, yi] = r[i], [xj, yj] = r[j]
        if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside
      }
    }
    if (inside) return true
  }
  return false
}

const bytes = new Uint8Array(Math.ceil((COLS * ROWS) / 8))
let ascii = "", count = 0
for (let r = 0; r < ROWS; r++) {
  for (let c = 0; c < COLS; c++) {
    const lon = LON_START + c * STEP, lat = LAT_START - r * STEP
    let hits = 0
    for (const dy of SAMPLES) for (const dx of SAMPLES) hits += onLand(lon + dx, lat + dy) ? 1 : 0
    const land = hits >= THRESHOLD
    if (land) { const i = r * COLS + c; bytes[i >> 3] |= 0x80 >> (i & 7); count++ }
    ascii += land ? "#" : "."
  }
  ascii += "\n"
}

const out = `/* Generated by scripts/build-world-dots.mjs from Natural Earth 110m land
   (world-atlas@2.0.2, public domain). One bit per ${STEP}° cell, row by row
   from latitude ${LAT_START}° and longitude ${LON_START}°: ${count} land dots. Do not edit by hand. */

export const WORLD_DOTS = {
  step: ${STEP},
  lonStart: ${LON_START},
  latStart: ${LAT_START},
  cols: ${COLS},
  rows: ${ROWS},
  bits: "${Buffer.from(bytes).toString("base64")}",
}
`
await writeFile(new URL("../lib/world-dots.ts", import.meta.url), out)
console.log(ascii)
console.log(`${count} land dots written to lib/world-dots.ts`)
